async fn search_external_sources(q: &str, source: &str, limit: usize) -> Vec<MidiTrack> {
    let mut results = Vec::new();
    let client = match reqwest::Client::builder().timeout(Duration::from_secs(3)).build() {
        Ok(c) => c,
        Err(_) => return results,
    };

    let need_bitmidi = source == "all" || source == "bitmidi";
    let need_midicollection = source == "all" || source == "midicollection";
    let need_midiworld = source == "all" || source == "midiworld";

    let bm_fut = async {
        if need_bitmidi {
            search_bitmidi_raw(&client, q, limit).await
        } else {
            Vec::new()
        }
    };
    let mc_fut = async {
        if need_midicollection {
            search_midicollection_raw(&client, q, limit).await
        } else {
            Vec::new()
        }
    };
    let mw_fut = async {
        if need_midiworld {
            search_midiworld_raw(&client, q, limit).await
        } else {
            Vec::new()
        }
    };

    let (bm, mc, mw) = tokio::join!(bm_fut, mc_fut, mw_fut);
    results.extend(bm);
    results.extend(mc);
    results.extend(mw);
    results
}

async fn search_bitmidi_raw(client: &reqwest::Client, q: &str, limit: usize) -> Vec<MidiTrack> {
    let mut tracks = Vec::new();
    let url = format!(
        "https://bitmidi.com/api/midi/search?q={}&page=0&pageSize={}",
        urlencoding_simple(q),
        limit.clamp(1, 20)
    );
    let Ok(resp) = client.get(&url).header("User-Agent", "Mozilla/5.0").send().await else {
        return tracks;
    };
    let Ok(json) = resp.json::<serde_json::Value>().await else {
        return tracks;
    };

    if let Some(items) = json.pointer("/result/results").and_then(|v| v.as_array()) {
        for item in items {
            let Some(id) = item.get("id").and_then(|v| v.as_u64()) else { continue };
            let raw_name = item.get("name").and_then(|v| v.as_str()).unwrap_or("MIDI Track");
            let clean_title = raw_name.trim_end_matches(".mid").trim_end_matches(".MID").replace('-', " ");
            let dl_url = format!("https://bitmidi.com/uploads/{id}.mid");
            tracks.push(MidiTrack {
                id: format!("bitmidi-{id}"),
                title: clean_title,
                artist: "BitMidi 全球曲库".to_string(),
                album: Some("BitMidi 开放库".to_string()),
                category: "western".to_string(),
                category_name: "欧美流行".to_string(),
                tags: vec!["BitMidi".to_string(), "全球曲库".to_string(), "海外".to_string()],
                duration_secs: 180,
                notes_count: 1200,
                difficulty: "中等".to_string(),
                file_size: 28000,
                play_count: item.get("plays").and_then(|v| v.as_u64()).unwrap_or(500) as u32,
                download_count: item.get("views").and_then(|v| v.as_u64()).unwrap_or(200) as u32,
                source: "bitmidi".to_string(),
                source_name: "BitMidi 全球曲库".to_string(),
                download_url: dl_url.clone(),
                preview_url: dl_url,
                description: Some("收录自 BitMidi 11万全球开放 MIDI 库".to_string()),
            });
            if tracks.len() >= limit {
                break;
            }
        }
    }
    tracks
}

async fn search_midicollection_raw(client: &reqwest::Client, q: &str, limit: usize) -> Vec<MidiTrack> {
    let mut tracks = Vec::new();
    let body = format!("page=1&search={}", urlencoding_simple(q));
    let Ok(resp) = client.post("https://midicollection.com/search")
        .header("User-Agent", "Mozilla/5.0")
        .header("Content-Type", "application/x-www-form-urlencoded; charset=UTF-8")
        .header("X-Requested-With", "XMLHttpRequest")
        .body(body)
        .send()
        .await else {
            return tracks;
        };
    let Ok(html) = resp.text().await else {
        return tracks;
    };

    // 从返回的 HTML 表格行截取 data-midi-id 与 data-url
    for part in html.split("<tr data-midi-id='").skip(1) {
        let Some((id_str, rest)) = part.split_once('\'') else { continue };
        let title = if let Some((_, t_rest)) = rest.split_once("data-title=\"") {
            t_rest.split_once('\"').map(|(t, _)| t).unwrap_or("MIDI")
        } else {
            "MIDI"
        };
        let rel_url = if let Some((_, u_rest)) = rest.split_once("data-url=\"") {
            u_rest.split_once('\"').map(|(u, _)| u).unwrap_or("")
        } else {
            continue
        };
        if rel_url.is_empty() {
            continue;
        }

        let full_dl = format!("https://midicollection.com{rel_url}");
        let clean_title = title.replace('_', " ").replace('-', " ");
        tracks.push(MidiTrack {
            id: format!("mc-{id_str}"),
            title: clean_title,
            artist: "MIDI Collection".to_string(),
            album: Some("MIDI Collection 16万曲库".to_string()),
            category: "western".to_string(),
            category_name: "欧美流行".to_string(),
            tags: vec!["MIDI Collection".to_string(), "开放曲库".to_string()],
            duration_secs: 200,
            notes_count: 1350,
            difficulty: "中等".to_string(),
            file_size: 32000,
            play_count: 3600,
            download_count: 1200,
            source: "midicollection".to_string(),
            source_name: "MIDI Collection (16万+ 开放曲库)".to_string(),
            download_url: full_dl.clone(),
            preview_url: full_dl,
            description: Some("收录自 MIDI Collection 16.7万曲目库".to_string()),
        });
        if tracks.len() >= limit {
            break;
        }
    }
    tracks
}

