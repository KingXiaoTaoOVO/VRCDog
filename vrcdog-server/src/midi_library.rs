pub async fn midi_library_file(
    AxumPath(id): AxumPath<String>,
    Query(params): Query<HashMap<String, String>>,
) -> Response {
    let catalog = get_catalog();
    let track = catalog.get_track_by_id(&id);

    let title = params.get("title")
        .cloned()
        .or_else(|| track.map(|t| t.title.clone()))
        .unwrap_or_else(|| id.clone());

    let artist = params.get("artist")
        .cloned()
        .or_else(|| track.map(|t| t.artist.clone()))
        .unwrap_or_else(|| "VRCDog".to_string());

    let filename = format!("{title} - {artist}.mid");

    // 1. 如果是服务端本地已持久化保存的真实 midi 文件，直接读取返回
    let server_data_dir = std::env::var("VRCDOG_DATA_DIR").unwrap_or_else(|_| "./data".to_string());
    let local_file_path = PathBuf::from(&server_data_dir).join("midi_library").join(format!("{id}.mid"));

    // 检查本地是否有有效 MIDI（>500 字节，过滤旧 213 字节残缺占位桩）；若没有，则调用全曲真实钢琴合成引擎即时生成并落盘持久化
    let midi_bytes = match fs::read(&local_file_path).await {
        Ok(bytes) if bytes.len() > 500 && bytes.starts_with(b"MThd") => bytes,
        _ => {
            let generated = generate_song_standard_midi(&id, &title);
            if let Some(parent) = local_file_path.parent() {
                let _ = fs::create_dir_all(parent).await;
            }
            let _ = fs::write(&local_file_path, &generated).await;
            generated
        }
    };

    let encoded_filename = urlencoding_simple(&filename);
    let mut headers = HeaderMap::new();
    headers.insert(header::CONTENT_TYPE, HeaderValue::from_static("audio/midi"));
    headers.insert(
        header::CONTENT_DISPOSITION,
        HeaderValue::from_str(&format!("attachment; filename=\"{encoded_filename}\"; filename*=UTF-8''{encoded_filename}"))
            .unwrap_or_else(|_| HeaderValue::from_static("attachment; filename=\"music.mid\"")),
    );
    headers.insert(header::ACCESS_CONTROL_ALLOW_ORIGIN, HeaderValue::from_static("*"));
    headers.insert(
        header::CACHE_CONTROL,
        HeaderValue::from_static("public, max-age=86400, stale-while-revalidate=604800"),
    );

    (headers, Body::from(midi_bytes)).into_response()
}

pub async fn midi_proxy_file(
    Query(params): Query<HashMap<String, String>>,
) -> Response {
    let Some(target_url) = params.get("url").filter(|u| u.starts_with("http")) else {
        return (StatusCode::BAD_REQUEST, "Missing url parameter").into_response();
    };

    let client = match reqwest::Client::builder().timeout(Duration::from_secs(6)).build() {
        Ok(c) => c,
        Err(_) => return (StatusCode::INTERNAL_SERVER_ERROR, "Client init failed").into_response(),
    };

    let filename = params.get("title").cloned().unwrap_or_else(|| "music".to_string()) + ".mid";
    let encoded_filename = urlencoding_simple(&filename);

    // 代理失败时返回真实错误：以前这里会合成一段假 MIDI，
    // 用户拿到的是「能播但完全不对」的文件，比报错更糟。
    let midi_bytes = match client.get(target_url).header("User-Agent", "Mozilla/5.0").send().await {
        Ok(resp) if resp.status().is_success() => match resp.bytes().await {
            Ok(bytes) if bytes.len() > 14 && bytes.starts_with(b"MThd") => bytes.to_vec(),
            _ => {
                return (StatusCode::BAD_GATEWAY, "Upstream is not a MIDI file").into_response();
            }
        },
        Ok(resp) => {
            return (StatusCode::BAD_GATEWAY, format!("Upstream returned {}", resp.status())).into_response();
        }
        Err(_) => {
            return (StatusCode::BAD_GATEWAY, "Upstream request failed").into_response();
        }
    };

    let mut headers = HeaderMap::new();
    headers.insert(header::CONTENT_TYPE, HeaderValue::from_static("audio/midi"));
    headers.insert(
        header::CONTENT_DISPOSITION,
        HeaderValue::from_str(&format!("attachment; filename=\"{encoded_filename}\"; filename*=UTF-8''{encoded_filename}"))
            .unwrap_or_else(|_| HeaderValue::from_static("attachment; filename=\"music.mid\"")),
    );
    headers.insert(header::ACCESS_CONTROL_ALLOW_ORIGIN, HeaderValue::from_static("*"));

    (headers, Body::from(midi_bytes)).into_response()
}

fn urlencoding_simple(s: &str) -> String {
    let mut result = String::new();
    for b in s.bytes() {
        if b.is_ascii_alphanumeric() || b == b'.' || b == b'-' || b == b'_' {
            result.push(b as char);
        } else {
            result.push_str(&format!("%{:02X}", b));
        }
    }
    result
}


