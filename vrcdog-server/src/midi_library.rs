pub async fn midi_library_search(
    Query(query): Query<MidiSearchQuery>,
) -> impl IntoResponse {
    let catalog = get_catalog();
    let q_raw = query.q.as_deref().unwrap_or("").trim();
    let src = query.source.as_deref().unwrap_or("all");
    let page = query.page.unwrap_or(1).max(1);
    let limit = query.limit.unwrap_or(20).clamp(1, 100);

    // 1. 本地精选全量多分词搜索
    let (curated_total, mut items) = catalog.search(&query);

    // 2. 如果输入了关键词，并且 (指定了第三方源 或 本地结果少于所需数量):
    //    异步并发请求 BitMidi / MidiCollection / MidiWorld
    if !q_raw.is_empty() && (src != "official" || items.is_empty()) {
        let external_items = search_external_sources(q_raw, src, limit).await;
        let mut seen = HashSet::new();
        for item in &items {
            seen.insert(normalize_for_search(&item.title));
        }
        for ext in external_items {
            let key = normalize_for_search(&ext.title);
            if seen.insert(key) {
                items.push(ext);
            }
        }
    }

    // 3. 没有结果就如实返回空列表：以前这里会凭空造一条「VRCDog 社区编配」曲目，
    //    连播放量/音符数都是假的，用户下载到的是一段与歌名无关的旋律。

    let total = items.len().max(curated_total);

    Json(json!({
        "success": true,
        "total": total,
        "page": page,
        "limit": limit,
        "categories": catalog.categories,
        "items": items,
    }))
}

